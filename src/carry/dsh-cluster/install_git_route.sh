#!/bin/bash
# INSIDE, CLUSTER ONLY. An alternative install for the batch cluster: let uv fetch
# each repo straight from GitLab-inside as a PINNED GIT SOURCE, instead of cloning
# them into src/ and installing them editable (install_packages.sh).
#
#   ./install_git_route.sh --workspace '<new-workspace-dir>'
#   ./install_git_route.sh --workspace '<new-workspace-dir>' --dry-run
#
# Why you might want it: a batch job should run exactly one known commit, and an
# editable checkout can be edited - or fast-forwarded - under a running job. A git
# source is a snapshot. Nothing here is editable; new code arrives as a new payload.
#
# WHAT IT DOES, and none of it touches an existing workspace:
#   1. checks uv, git and the credential - non-interactively, so a missing credential
#      is a RESULT rather than a prompt that hangs a batch shell
#   2. writes <workspace>/pyproject.toml: every KIT_REPOS entry as a dependency
#      (with its KIT_EXTRAS), each sourced from GitLab at the EXACT commit
#      MANIFEST.txt records. A pyproject.dsh-cluster.toml in the payload, if there
#      is one, is used instead, with <group> substituted.
#   3. uv sync   (the first run also writes uv.lock)
#   4. checks the packages import, the console scripts resolve, and NOTHING is editable
#   5. checks the commits uv pinned against MANIFEST.txt
#
# Re-running it after a new payload rewrites the root to the new commits and
# re-syncs: that is the update path.
#
# IT IS A SECOND WORKSPACE, NOT A REPLACEMENT. Point --workspace at a NEW directory.
# An install_packages.sh workspace keeps working and stays the place to debug,
# because a git source cannot be edited in place. This script REFUSES a directory
# that already holds one.
#
# Linux only. The Desktop VM is where the editing happens, so it stays on clones.
#
# Log: Logs/install_git_route.log in the payload.

set -uo pipefail

if [ "${BASH_SOURCE[0]}" != "$0" ]; then
    echo "Run this script instead of sourcing it:   ./$(basename "${BASH_SOURCE[0]}")" >&2
    return 1 2>/dev/null || exit 1
fi

PAYLOAD_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# shellcheck source=../any/lib/dsh_log.sh
. "${PAYLOAD_DIR}/lib/dsh_log.sh"
dsh_start_log "$@"

# shellcheck source=../any/lib/dsh_platform.sh
. "${PAYLOAD_DIR}/lib/dsh_platform.sh"
dsh_kit_settings "$PAYLOAD_DIR" || exit 1
dsh_gitlab_only "$(basename "$0")" || exit 0

WORKSPACE=""
GROUP="$KIT_GITLAB_GROUP"
GITLAB_HOST="$KIT_GITLAB_HOST"
WORKING_NAMESPACE="$KIT_WORKING_NAMESPACE"
PYTHON="$KIT_PYTHON"
FORCE=0
DRY=0
# The marker that says a pyproject.toml is one this script wrote, and so may be
# rewritten without --force.
MARKER="# Generated by install_git_route.sh"

usage() {
    sed -n '2,36p' "$0"
    echo
    echo "Usage: $0 --workspace DIR [options]"
    echo
    echo "  --workspace DIR   a NEW directory for the git-route workspace"
    echo "  --python PATH     interpreter for the first sync (default: KIT_PYTHON)"
    echo "  --group NAME      default from the conf: ${KIT_GITLAB_GROUP}"
    echo "  --gitlab HOST     default from the conf: ${KIT_GITLAB_HOST}"
    echo "  --working-namespace NS   where the working repos live (default: the group)"
    echo "  --force           overwrite a pyproject.toml this script did not write"
    echo "  --dry-run         run every check and write the root, stop before uv sync"
    exit 1
}

while [ $# -gt 0 ]; do
    case "$1" in
        --workspace) WORKSPACE="$2"; shift 2 ;;
        --python)    PYTHON="$2";    shift 2 ;;
        --group)     GROUP="$2";     shift 2 ;;
        --gitlab)    GITLAB_HOST="$2"; shift 2 ;;
        --working-namespace) WORKING_NAMESPACE="$2"; shift 2 ;;
        --force)     FORCE=1; shift ;;
        --dry-run)   DRY=1; shift ;;
        -h|--help)   usage ;;
        *) echo "Unknown argument: $1" >&2; usage ;;
    esac
done

[ -n "$WORKSPACE" ] || { echo "Error: --workspace is required - a NEW directory" >&2; usage; }
[ -n "$GROUP" ]     || { echo "Error: no GitLab group - set KIT_GITLAB_GROUP or pass --group" >&2; usage; }
dsh_no_placeholder KIT_GITLAB_GROUP "$GROUP" || exit 1

# Publish host / group / working namespace for dsh_repo_remote, which reads them
# from the environment so that one function assembles every URL in every carried
# script. It has to come after dsh_platform.sh is sourced, above.
dsh_gitlab_env "$GITLAB_HOST" "$GROUP" "$WORKING_NAMESPACE"

if [ "$DSH_OS" != "linux" ]; then
    echo "Error: this is the CLUSTER route and this box is ${DSH_OS}." >&2
    echo "The Desktop VM installs from clones - install_packages.sh - because that is" >&2
    echo "where packages get edited, and a git source cannot be edited in place." >&2
    exit 1
fi

MANIFEST="${PAYLOAD_DIR}/MANIFEST.txt"
[ -s "$MANIFEST" ] || { echo "Error: ${MANIFEST} missing or empty - nothing to pin to" >&2; exit 1; }
manifest_sha() { awk -v p="$1" '$1==p {print $3}' "$MANIFEST"; }

# shellcheck disable=SC2206
PACKAGES=($KIT_REPOS)
# shellcheck disable=SC2206
MODULES=($KIT_IMPORT_CHECK)
# shellcheck disable=SC2206
CONSOLE_SCRIPTS=($KIT_CONSOLE_SCRIPTS)

FAIL=0
hr() { echo; echo "=== $* ==="; }

echo "install_git_route"
printf '  %-16s %s\n' "workspace" "$WORKSPACE"
printf '  %-16s %s\n' "gitlab"    "$GITLAB_HOST"
printf '  %-16s %s\n' "group"     "$GROUP"
printf '  %-16s %s\n' "repos"     "${PACKAGES[*]}"

hr "1. Tools"
export PATH="${HOME}/.local/bin:${PATH}"
UV="$(command -v "$DSH_UV_EXE" 2>/dev/null || echo "${HOME}/.local/bin/${DSH_UV_EXE}")"
if [ -x "$UV" ]; then
    printf '  %-16s %s\n' "uv" "$UV ($("$UV" --version 2>&1))"
else
    echo "  uv NOT FOUND - run ./install_uv.sh first" >&2
    exit 1
fi
if command -v git >/dev/null 2>&1; then
    printf '  %-16s %s\n' "git" "$(git --version)"
else
    echo "  git NOT FOUND - uv clones by shelling out to git, so this route needs it" >&2
    exit 1
fi
dsh_git_guard || FAIL=1

hr "2. The credential"
# THE gate on this route. uv shells out to git with prompts disabled, so an
# interactive password cannot work here. Asking git the same way uv will, with
# GIT_TERMINAL_PROMPT=0, turns "no credential" into an answer instead of a shell
# that sits waiting for a username nobody is there to type.
helper="$(git config --global --get credential.helper 2>/dev/null)"
printf '  %-16s %s\n' "helper" "${helper:-<none configured>}"
probe_url="$(dsh_repo_remote "${PACKAGES[0]}")" || exit 1
printf '  %-16s ' "ls-remote"
if GIT_TERMINAL_PROMPT=0 git ls-remote "$probe_url" HEAD > "${PAYLOAD_DIR}/.lsr.txt" 2>&1; then
    echo "OK - $(awk '{print substr($1,1,8)}' "${PAYLOAD_DIR}/.lsr.txt" | head -1)"
else
    echo "FAILED"
    sed 's/^/      /' "${PAYLOAD_DIR}/.lsr.txt" | tail -6
    echo
    echo "  'could not read Username ... terminal prompts disabled' means no stored"
    echo "  credential, which is expected on a first run and is not a fault. Store one:"
    echo "      git config --global credential.helper 'store --file ~/.git-credentials'"
    echo "      printf 'https://<user>:<token>@${GITLAB_HOST}\\n' > ~/.git-credentials"
    echo "      chmod 600 ~/.git-credentials"
    echo "  A plaintext store is acceptable HERE and not on the VM because a batch"
    echo "  job has no terminal for the in-memory cache to have been filled from."
    echo "  The DSH GitLab token permission is 'Repository > Code (Download)' - this"
    echo "  instance uses the granular token UI, so read_repository is not on offer."
    echo "  A 404 on a project that exists usually means the token lacks it too."
    FAIL=1
fi
rm -f "${PAYLOAD_DIR}/.lsr.txt"

hr "3. The workspace directory"
# Refuse to convert a clone-route workspace in place. Its src/ holds clones that
# install_packages.sh maintains; overwriting its root would leave those on disk,
# unreferenced and stale, while uv silently resolved the same names from GitLab. Two
# sources of truth for the same package is the failure this whole scheme exists to
# prevent.
for pkg in "${PACKAGES[@]}"; do
    if [ -d "${WORKSPACE}/src/${pkg}/.git" ]; then
        echo "  REFUSING: ${WORKSPACE} is a CLONE-route workspace (src/${pkg} is a clone)." >&2
        echo "  The git route is a second workspace, not a conversion. Give --workspace a" >&2
        echo "  new directory and keep this one - it stays the place to debug packages," >&2
        echo "  because a git source is pinned and cannot be edited in place." >&2
        exit 1
    fi
done
mkdir -p "$WORKSPACE" || { echo "  Cannot create ${WORKSPACE}" >&2; exit 1; }
WORKSPACE="$(cd "$WORKSPACE" && pwd)"
DEST_ROOT="${WORKSPACE}/pyproject.toml"
if [ -f "$DEST_ROOT" ] && [ "$FORCE" -eq 0 ]; then
    if grep -qF "$MARKER" "$DEST_ROOT" 2>/dev/null; then
        echo "  ${DEST_ROOT} is one this script wrote - it will be rewritten."
    else
        echo "  REFUSING: ${DEST_ROOT} exists and is NOT a git-route root." >&2
        echo "  Re-run with --force to overwrite it, or pick another --workspace." >&2
        exit 1
    fi
fi
echo "  ${WORKSPACE} - usable"

hr "4. Every repo is pinnable"
for pkg in "${PACKAGES[@]}"; do
    printf '  %-26s ' "$pkg"
    sha="$(manifest_sha "$pkg")"
    if [ -n "$sha" ]; then
        echo "${sha:0:8}  ($(dsh_repo_remote "$pkg"))"
    else
        echo "NOT IN MANIFEST.txt - no commit to pin it to"
        FAIL=1
    fi
done

if [ "$FAIL" -ne 0 ]; then
    echo
    echo "RESULT: FAIL - a precondition above is not met. Nothing was written." >&2
    exit 1
fi

hr "5. Writing the root"
extras_for() {
    local spec
    for spec in $KIT_EXTRAS; do
        case "$spec" in "$1["*"]") printf '%s' "${spec#"$1"}"; return 0 ;; esac
    done
}
if [ -f "${PAYLOAD_DIR}/pyproject.dsh-cluster.toml" ]; then
    # A hand-written root wins. sed on <group> only: every other value in it is
    # the author's, and rewriting more of it here would put the real configuration
    # in a shell script instead of in the file the operator can read.
    { echo "$MARKER (from pyproject.dsh-cluster.toml)"
      sed "s|<group>|${GROUP}|g" "${PAYLOAD_DIR}/pyproject.dsh-cluster.toml"; } > "$DEST_ROOT" || exit 1
    echo "  from the payload's pyproject.dsh-cluster.toml"
else
    # rev = the exact commit, not a branch: the cluster runs what the payload
    # carried, and a new payload is the only way new code arrives. A branch would
    # let `uv lock --upgrade` move past what the manifest describes.
    {
        echo "$MARKER from dsh-kit.conf and MANIFEST.txt. Re-run it; do not edit."
        echo "[project]"
        echo "name = \"${KIT_PROJECT}-git-route\""
        echo "version = \"0.0.0\""
        [ -n "$KIT_PYTHON_SPEC" ] && echo "requires-python = \"${KIT_PYTHON_SPEC}\""
        echo "dependencies = ["
        for pkg in "${PACKAGES[@]}"; do
            echo "    \"${pkg}$(extras_for "$pkg")\","
        done
        echo "]"
        echo
        echo "[tool.uv]"
        echo "package = false"
        echo
        # Every first-party name needs its own entry: [tool.uv.sources] is not
        # transitive, so a git-sourced package's own first-party dependencies are
        # redirected only because they are listed here too.
        echo "[tool.uv.sources]"
        for pkg in "${PACKAGES[@]}"; do
            echo "${pkg} = { git = \"$(dsh_repo_remote "$pkg")\", rev = \"$(manifest_sha "$pkg")\" }"
        done
    } > "$DEST_ROOT"
    echo "  generated from dsh-kit.conf"
fi
if grep -q '<group>' "$DEST_ROOT"; then
    echo "  FAILED - '<group>' still present after substitution" >&2
    exit 1
fi
echo "  ${DEST_ROOT}"
grep -A20 '^\[tool.uv.sources\]' "$DEST_ROOT" | sed 's/^/    /'

SYNC_ARGS=(sync)
[ -n "$PYTHON" ] && SYNC_ARGS+=(--python "$PYTHON")

if [ "$DRY" -eq 1 ]; then
    echo
    echo "RESULT: DRY RUN - the root is written and every precondition passed."
    echo "  Run without --dry-run to sync, or by hand:"
    echo "      cd '${WORKSPACE}' && '${UV}' ${SYNC_ARGS[*]}"
    exit 0
fi

hr "6. uv ${SYNC_ARGS[*]}"
echo "  (first run clones every repo and resolves the third-party set - minutes, not seconds)"
cd "$WORKSPACE" || exit 1
if ! "$UV" "${SYNC_ARGS[@]}"; then
    echo >&2
    echo "RESULT: FAIL - uv sync did not complete." >&2
    echo "  'not found in the package registry' naming a FIRST-PARTY package" >&2
    echo "     -> a repo depends on a first-party name that is not in KIT_REPOS, so it" >&2
    echo "        has no [tool.uv.sources] entry and uv looked for it on Artifactory." >&2
    echo "  an auth error   -> the credential expired. Section 2 passed at the time," >&2
    echo "                     so re-check the token's expiry date." >&2
    echo "  a revision error -> GitLab does not have that commit: the VM has not" >&2
    echo "                     mirrored this payload yet. Run update_dsh_vm.bat there." >&2
    echo "  a THIRD-PARTY name -> Artifactory has not mirrored it. Write down which." >&2
    exit 1
fi

VENV_PY="${WORKSPACE}/.venv/${DSH_VENV_PYTHON}"
[ -x "$VENV_PY" ] || { echo "uv sync finished but there is no interpreter at ${VENV_PY}" >&2; exit 1; }

hr "7. Do the packages import, and is anything editable"
printf '  %-26s ' "interpreter"
"$VENV_PY" -c "import sys,platform; print(sys.version.split()[0], platform.machine())" || exit 1
rc=0
for mod in "${MODULES[@]}"; do
    printf '  %-26s ' "$mod"
    if "$VENV_PY" -c "import ${mod}" > "${PAYLOAD_DIR}/gitroute_err_${mod}.txt" 2>&1; then
        echo "OK"
        rm -f "${PAYLOAD_DIR}/gitroute_err_${mod}.txt"
    else
        echo "FAILED"
        sed 's/^/      /' "${PAYLOAD_DIR}/gitroute_err_${mod}.txt" | tail -8
        rc=1
    fi
done

# A git source must land IN site-packages. If a path outside the venv shows up, some
# earlier editable install is still winning and the sync did not do what it looks
# like it did - the code being imported would then be whatever is on disk there,
# not the commit uv pinned, and every claim about reproducibility below is void.
printf '  %-26s ' "not editable"
editable="$("$VENV_PY" - "${MODULES[@]}" <<'PYEOF'
import importlib, sys
bad = []
for name in sys.argv[1:]:
    try:
        m = importlib.import_module(name)
    except Exception:
        continue
    if "site-packages" not in (getattr(m, "__file__", "") or ""):
        bad.append(name)
print(",".join(bad))
PYEOF
)"
if [ -z "$editable" ]; then
    echo "OK - imported from site-packages"
else
    echo "NO - imported from outside site-packages: ${editable}"
    echo "      A git source is a snapshot; an editable install shadowing it means the"
    echo "      code running is not the commit uv.lock pins."
    rc=1
fi

if [ "${#CONSOLE_SCRIPTS[@]}" -gt 0 ]; then
    hr "8. Do the console scripts resolve"
    # The .exe launcher problem is Windows-only, so on this box a console script
    # that fails is a real failure. Resolved through importlib.metadata rather than
    # run off PATH: PATH may still hold another venv's copies, and those would answer.
    for name in "${CONSOLE_SCRIPTS[@]}"; do
        printf '  %-26s ' "$name"
        if "$VENV_PY" -c '
import sys
from importlib.metadata import entry_points
name = sys.argv[1]
eps = [e for e in entry_points(group="console_scripts") if e.name == name]
if not eps:
    print("not installed by any package in this venv")
    raise SystemExit(1)
sys.argv = [name, "--help"]
raise SystemExit(eps[0].load()())
' "$name" > "${PAYLOAD_DIR}/gitroute_ep_${name}.txt" 2>&1; then
            echo "OK"
            rm -f "${PAYLOAD_DIR}/gitroute_ep_${name}.txt"
        else
            echo "FAILED"
            sed 's/^/      /' "${PAYLOAD_DIR}/gitroute_ep_${name}.txt" | tail -8
            rc=1
        fi
    done
fi

hr "9. What uv pinned, against MANIFEST.txt"
# The point of bundling real git history: a commit id means the same thing on both
# sides of the airlock. So the SHAs uv resolved from GitLab must be the SHAs the
# payload says were pushed. With a generated root that is true by construction; a
# hand-written pyproject.dsh-cluster.toml that tracks a branch is where it is not,
# and a mismatch then means GitLab was never refreshed with this payload - this
# venv is built from older code that will still import cleanly.
if [ ! -s "${WORKSPACE}/uv.lock" ]; then
    echo "  uv.lock missing or empty after a successful sync - that should not happen." >&2
    rc=1
else
    for pkg in "${PACKAGES[@]}"; do
        printf '  %-26s ' "$pkg"
        # uv writes the resolved commit as the fragment of the git URL.
        # Reset at every [[package]] header. Without that, a package with no git
        # source leaves the flag set and the NEXT package's commit is reported
        # under this name - a wrong answer wearing the shape of a right one.
        got="$(awk -v p="$pkg" '
            /^\[\[package\]\]/ {f=0}
            $0 ~ "^name = \"" p "\"$" {f=1; next}
            f && /source = \{ git =/ {print; exit}
        ' "${WORKSPACE}/uv.lock" | sed 's/.*#\([0-9a-f]*\).*/\1/')"
        want="$(manifest_sha "$pkg")"
        if [ -z "$got" ]; then
            echo "no git source in uv.lock - resolved from somewhere else"
            rc=1
        elif [ "$got" = "$want" ]; then
            echo "${got:0:8} matches manifest"
        else
            echo "MISMATCH: pinned ${got:0:8}, manifest says ${want:0:8}"
            rc=1
        fi
    done
fi

hr "Verdict"
if [ "$rc" -eq 0 ]; then
    echo "  PASS - the git route is installed and pinned to the payload's commits."
    echo
    printf '  %-16s %s\n' "workspace" "$WORKSPACE"
    printf '  %-16s %s\n' "python"    "$VENV_PY"
    printf '  %-16s %s\n' "uv.lock"   "${WORKSPACE}/uv.lock  - keep it, it IS the pin"
    echo
    echo "  Nothing here is editable. To pick up new work: carry a new payload in,"
    echo "  mirror it from the VM, copy the payload folder here, and re-run this."
    echo
    echo "  Point your job scripts at this venv:"
    echo "      ${VENV_PY}"
    echo "  and generate any per-machine configuration ON this box - never copy it"
    echo "  from the VM, where paths and drives differ."
    exit 0
fi
echo "  FAIL - see the section above. The workspace exists and uv.lock is written," >&2
echo "  so re-running after a fix re-uses the resolution rather than starting over." >&2
exit 1
