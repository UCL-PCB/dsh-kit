#!/bin/bash
# INSIDE. The console-script .exe stubs will not run from the share. Replace
# them with wrappers that call the same function directly.
#
# Established by diagnose/diagnose_import_chain.sh, and worth restating because it is
# narrow: the whole import chain loads, the entry-point function runs correctly
# when python imports and calls it, and only the generated .exe fails, with
# "DLL load failed ... The parameter is incorrect". Every console script is
# affected equally. Nothing is wrong with the mirror, the install, the extras or
# the packaging - the launcher stub is a small executable that cannot be loaded
# across SMB.
#
# So: keep the venv where it is, and stop going through the stub. For each entry
# point this writes a one-line bash wrapper that runs
#
#     <venv python> -c 'from <module> import <func>; func()' "$@"
#
# into a bin directory on local disk. Same code path the in-process test already
# proved works, same name on PATH, so anything calling the script by name
# keeps working without knowing.
#
# STATE-CHANGING, but only by adding files to the bin directory - it never
# touches the venv, the workspace or the .exe stubs, and deleting the wrappers
# undoes it completely.
#
#   ./make_console_wrappers.sh          # workspace from ~/dsh-kit.env (KIT_WORKSPACE_DIR)
#   ./make_console_wrappers.sh --workspace '/s/<share>/<workspace-dir>'
#   ./make_console_wrappers.sh --workspace ... --bin-dir ~/.local/bin
#
# ~/.local/bin is the default because install_uv.sh already put it on PATH.
# It must be on LOCAL disk: a wrapper is a text file, so the share cannot break
# it the way it breaks the stubs, but keeping bin off the share is one less
# thing to reason about.
#
# Log: Logs/make_console_wrappers.log beside this script.

set -uo pipefail

if [ "${BASH_SOURCE[0]}" != "$0" ]; then
    echo "Run this script instead of sourcing it:   ./$(basename "${BASH_SOURCE[0]}")" >&2
    return 1 2>/dev/null || exit 1
fi

PAYLOAD_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# shellcheck source=../any/lib/dsh_log.sh
. "${PAYLOAD_DIR}/lib/dsh_log.sh"
dsh_start_log "$@"

# shellcheck source=../any/lib/dsh_platform.sh
. "${PAYLOAD_DIR}/lib/dsh_platform.sh"
# Which repos to read entry points from: KIT_REPOS in dsh-kit.conf.
dsh_kit_settings "$PAYLOAD_DIR" || exit 1

WORKSPACE="$KIT_WORKSPACE_DIR"
BIN_DIR="${HOME}/.local/bin"

usage() {
    sed -n '2,38p' "$0"
    echo
    echo "Usage: $0 --workspace DIR [--bin-dir DIR]"
    exit 1
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --workspace) WORKSPACE="$2"; shift 2 ;;
        --bin-dir)   BIN_DIR="$2";   shift 2 ;;
        -h|--help)   usage ;;
        *) echo "Unknown argument: $1" >&2; usage ;;
    esac
done
[ -n "$WORKSPACE" ] || { echo "Error: --workspace is required (or KIT_WORKSPACE_DIR in ~/dsh-kit.env)" >&2; usage; }

hr() { echo; echo "=== $* ==="; }

VENV_PY="${WORKSPACE}/.venv/${DSH_VENV_PYTHON}"
[ -f "$VENV_PY" ] || { echo "No venv interpreter at ${VENV_PY}" >&2; exit 1; }
mkdir -p "$BIN_DIR" || { echo "Cannot create ${BIN_DIR}" >&2; exit 1; }

echo "make_console_wrappers"
echo "  venv:    ${VENV_PY}"
echo "  bin dir: ${BIN_DIR}"

hr "1. Entry points declared by the installed packages"
# Read them out of the pyproject that is actually installed, not a list kept
# here - a hardcoded list goes stale the moment a new console script is added,
# and would silently leave it unwrapped.
ENTRIES="${PAYLOAD_DIR}/.entries.txt"
: > "$ENTRIES"
for pkg in $KIT_REPOS; do
    f="${WORKSPACE}/src/${pkg}/pyproject.toml"
    [ -f "$f" ] || continue
    # Everything between [project.scripts] and the next [section] header.
    awk '/^\[project\.scripts\]/{f=1;next} /^\[/{f=0} f && /=/{print}' "$f" \
        | sed 's/[[:space:]]//g; s/"//g' >> "$ENTRIES"
done
count="$(grep -c '=' "$ENTRIES" 2>/dev/null || echo 0)"
if [ "${count:-0}" -eq 0 ]; then
    echo "  none found - is --workspace right? expected ${WORKSPACE}/src/<pkg>/pyproject.toml" >&2
    rm -f "$ENTRIES"
    exit 1
fi
sed 's/^/    /' "$ENTRIES"
echo "  ${count} entry point(s)"

hr "2. Writing wrappers"
written=0
while IFS='=' read -r name target; do
    [ -n "$name" ] && [ -n "$target" ] || continue
    module="${target%%:*}"
    func="${target##*:}"
    dest="${BIN_DIR}/${name}"
    # sys.argv[0] is "-c" under python -c, which argparse would print as the
    # program name in usage and errors. Setting it keeps --help honest.
    cat > "$dest" <<WRAPPER
#!/bin/bash
# Generated by make_console_wrappers.sh. Calls the entry point directly,
# because the .exe stub for it cannot be loaded from the share.
exec "${VENV_PY}" -c 'import sys; sys.argv[0]="${name}"; from ${module} import ${func}; sys.exit(${func}())' "\$@"
WRAPPER
    chmod +x "$dest"
    printf '    %-26s -> %s:%s\n' "$name" "$module" "$func"
    written=$((written + 1))
done < "$ENTRIES"
head -1 "$ENTRIES" > "${PAYLOAD_DIR}/.entries.first"
rm -f "$ENTRIES"
echo "  ${written} wrapper(s) written"

hr "3. Do they run?"
# --help through the wrapper is the same check install_packages.sh does, minus
# the stub.
rc=0
#
# ONE script, not all of them: the first of KIT_CONSOLE_SCRIPTS, or else the
# first wrapper written. A heavy import chain can take the best part of a minute,
# longer again across SMB, and the finding this acts on is that every console
# script fails IDENTICALLY - so a second one tells you nothing the first did not.
probe="${KIT_CONSOLE_SCRIPTS%% *}"
[ -n "$probe" ] || probe="$(awk -F= 'NF==2 {print $1; exit}' "${PAYLOAD_DIR}/.entries.first" 2>/dev/null)"
echo "  (can take a minute if the entry point's imports are heavy)"
for name in $probe; do
    printf '  %-26s ' "$name"
    if [ ! -f "${BIN_DIR}/${name}" ]; then
        echo "not generated (not declared by any installed package)"
        continue
    fi
    if "${BIN_DIR}/${name}" --help > "${PAYLOAD_DIR}/.w.out" 2>&1; then
        echo "OK"
    else
        echo "FAILED"
        sed 's/^/      /' "${PAYLOAD_DIR}/.w.out" | tail -12
        rc=1
    fi
done
rm -f "${PAYLOAD_DIR}/.w.out" "${PAYLOAD_DIR}/.entries.first"

hr "4. Is the bin directory ahead of the venv's Scripts on PATH?"
# If the venv's Scripts dir comes first, the broken .exe still wins and the
# wrappers are never reached - which would look exactly like this fix failing.
first=""
SCRIPTS_DIR="$(dirname "$VENV_PY")"
# read, not word-splitting: Windows PATH entries contain spaces.
while IFS= read -r d; do
    case "$d" in
        "$BIN_DIR")     first="wrapper"; break ;;
        "$SCRIPTS_DIR") first="venv";    break ;;
    esac
done < <(echo "$PATH" | tr ':' '
')
case "$first" in
    wrapper) echo "  yes - ${BIN_DIR} comes first, the wrappers win" ;;
    venv)    echo "  NO - the venv's Scripts directory comes first, so the broken"
             echo "  .exe still wins. Put the wrappers ahead of it:"
             echo "      export PATH=\"${BIN_DIR}:\$PATH\"" ;;
    *)       echo "  ${BIN_DIR} is not on PATH at all. Add it:"
             echo "      export PATH=\"${BIN_DIR}:\$PATH\""
             echo "      echo 'export PATH=\"${BIN_DIR}:\$PATH\"' >> ~/.bashrc" ;;
esac

hr "Verdict"
if [ "$rc" -eq 0 ] && [ "$written" -gt 0 ]; then
    echo "  ${written} console scripts are callable again. Section 3 is the check -"
    echo "  install_packages.sh will still report 'STUB FAILED, function OK' on"
    echo "  every re-run, because it tests the stubs, and that is now expected."
    echo
    echo "  Call them by NAME from now on - 'uv run <script>' does NOT work here."
    echo "  uv run resolves the console script's .exe inside .venv/Scripts and execs"
    echo "  it directly, so it never reaches these wrappers whatever PATH says, and"
    echo "  fails with the same 'DLL load failed ... The parameter is incorrect'."
    echo "      <script> --help          # yes"
    echo "      uv run <script> --help   # no, fails"
    echo
    echo "  Make it stick across sessions (Citrix drops after 18 h):"
    echo "      echo 'export PATH=\"${BIN_DIR}:\$PATH\"' >> ~/.bashrc"
    echo
    echo "  Note for the cluster trip: this is a Windows launcher problem and"
    echo "  does not exist on Linux. Do not carry these wrappers over."
    exit 0
fi
echo "  The wrappers did not run. Section 3 has the error. If it is the same"
echo "  DLL failure, the wrapper is not the fix and the venv has to move to"
echo "  local disk after all - re-run install_packages.sh with --workspace on a"
echo "  local path and keep the DATA on S:."
exit 1
